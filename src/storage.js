function getTodayDateString() {
    const now = new Date();
    return now.toISOString().split('T')[0]; // YYYY-MM-DD
}

function getTodayLimits() {
    const limits = getLimits();
    const today = getTodayDateString();

    // Find today's entry
    const todayEntry = limits.data.find(entry => entry.date === today);

    if (todayEntry) {
        // ensure new fields exist
        if (!todayEntry.groq) {
            todayEntry.groq = {
                'qwen3-32b': { chars: 0, limit: 1500000 },
                'gpt-oss-120b': { chars: 0, limit: 600000 },
                'gpt-oss-20b': { chars: 0, limit: 600000 },
                'kimi-k2-instruct': { chars: 0, limit: 600000 },
            };
        }
        if (!todayEntry.gemini) {
            todayEntry.gemini = {
                'gemma-4-26b-a4b-it': { chars: 0 },
            };
        }
        setLimits(limits);
        return todayEntry;
    }

    // No entry for today - clean old entries and create new one
    limits.data = limits.data.filter(entry => entry.date === today);
    const newEntry = {
        date: today,
        flash: { count: 0 },
        flashLite: { count: 0 },
        groq: {
            'qwen3-32b': { chars: 0, limit: 1500000 },
            'gpt-oss-120b': { chars: 0, limit: 600000 },
            'gpt-oss-20b': { chars: 0, limit: 600000 },
            'kimi-k2-instruct': { chars: 0, limit: 600000 },
        },
        gemini: {
            'gemma-4-26b-a4b-it': { chars: 0 },
        },
    };
    limits.data.push(newEntry);
    setLimits(limits);

    return newEntry;
}

function incrementLimitCount(model) {
    const limits = getLimits();
    const today = getTodayDateString();

    // Find or create today's entry
    let todayEntry = limits.data.find(entry => entry.date === today);

    if (!todayEntry) {
        // Clean old entries and create new one
        limits.data = [];
        todayEntry = {
            date: today,
            flash: { count: 0 },
            flashLite: { count: 0 },
        };
        limits.data.push(todayEntry);
    } else {
        // Clean old entries, keep only today
        limits.data = limits.data.filter(entry => entry.date === today);
    }

    // Increment the appropriate model count
    if (model.includes('flash-lite')) {
        todayEntry.flashLite.count++;
    } else if (model.includes('flash')) {
        todayEntry.flash.count++;
    }

    setLimits(limits);
    return todayEntry;
}

function incrementCharUsage(provider, model, charCount) {
    getTodayLimits();

    const limits = getLimits();
    const today = getTodayDateString();
    const todayEntry = limits.data.find(entry => entry.date === today);

    if (todayEntry[provider] && todayEntry[provider][model]) {
        todayEntry[provider][model].chars += charCount;
        setLimits(limits);
    }

    return todayEntry;
}

// Free tier gives 20 requests/day per model, so each model in this list adds its own quota.
// gemini-2.5-* is gone for new users (404) and gemini-3.8-flash is often overloaded (503).
const DEFAULT_GEMINI_MODEL = 'gemini-3.5-flash';
const GEMINI_FALLBACK_MODELS = [
    DEFAULT_GEMINI_MODEL,
    'gemini-3.6-flash',
    'gemini-3.7-flash',
    'gemini-3-flash-preview',
    'gemini-3.8-flash',
    'gemini-3.5-flash-lite',
    'gemini-3.1-flash-lite',
];
const GEMINI_FREE_DAILY_REQUESTS = 20;

function getGeminiQuotaPath() {
    return path.join(getConfigDir(), 'gemini-quota.json');
}

// Google resets free tier quotas at midnight Pacific time
function getPacificDateString() {
    return new Date().toLocaleDateString('en-CA', { timeZone: 'America/Los_Angeles' });
}

// { date, models: { [model]: { used, blockedUntil } } }, reset when the Pacific day changes
function getGeminiQuota() {
    const today = getPacificDateString();
    const quota = readJsonFile(getGeminiQuotaPath(), null);
    if (!quota || quota.date !== today || !quota.models) {
        return { date: today, models: {} };
    }
    return quota;
}

function updateGeminiModelQuota(model, update) {
    const quota = getGeminiQuota();
    quota.models[model] = update({ used: 0, ...quota.models[model] });
    writeJsonFile(getGeminiQuotaPath(), quota);
}

function recordGeminiModelSuccess(model) {
    updateGeminiModelQuota(model, entry => ({ ...entry, used: entry.used + 1 }));
}

function markModelUnavailable(model, retryAfterMs) {
    updateGeminiModelQuota(model, entry => ({ ...entry, blockedUntil: Date.now() + retryAfterMs }));
}

// Model chosen in settings goes first. Lite models answer in ~3s, flash models think ~10s first,
// so the rest of the chain keeps the same kind (lite or flash) as the chosen model before the other kind.
function getOrderedGeminiModels() {
    const prefs = getPreferences();
    // Older configs stored a "fast answers" toggle instead of a model
    const preferred = GEMINI_FALLBACK_MODELS.includes(prefs.geminiModel)
        ? prefs.geminiModel
        : prefs.fastAnswers
          ? 'gemini-3.5-flash-lite'
          : DEFAULT_GEMINI_MODEL;
    const rest = GEMINI_FALLBACK_MODELS.filter(model => model !== preferred);
    const sameKind = rest.filter(model => isLiteModel(model) === isLiteModel(preferred));
    const otherKind = rest.filter(model => isLiteModel(model) !== isLiteModel(preferred));
    return [preferred, ...sameKind, ...otherKind];
}

function isLiteModel(model) {
    return model.includes('flash-lite');
}

function getModelRemaining(entry, now) {
    if (entry?.blockedUntil > now) return 0;
    return Math.max(0, GEMINI_FREE_DAILY_REQUESTS - (entry?.used || 0));
}

function getAvailableModel() {
    return getModelFallbackChain()[0];
}

// Models to try in order: ones with quota left first, then unblocked ones (paid keys can exceed 20).
// If every model is blocked, still try them all rather than failing without a request.
function getModelFallbackChain() {
    const now = Date.now();
    const { models } = getGeminiQuota();
    const ordered = getOrderedGeminiModels();
    const withQuota = ordered.filter(model => getModelRemaining(models[model], now) > 0);
    const unblocked = ordered.filter(model => !(models[model]?.blockedUntil > now) && !withQuota.includes(model));
    const chain = [...withQuota, ...unblocked];
    return chain.length > 0 ? chain : [...ordered];
}

// Estimated requests left today across all models (only counts requests made by this app)
function getGeminiQuotaSummary() {
    const now = Date.now();
    const { models } = getGeminiQuota();
    const remaining = GEMINI_FALLBACK_MODELS.reduce((sum, model) => sum + getModelRemaining(models[model], now), 0);
    return { remaining, total: GEMINI_FALLBACK_MODELS.length * GEMINI_FREE_DAILY_REQUESTS, nextModel: getAvailableModel() };
}

function getModelForToday() {
    const todayEntry = getTodayLimits();
    const groq = todayEntry.groq;

    if (groq['gpt-oss-120b'].chars < groq['gpt-oss-120b'].limit) {
        return 'openai/gpt-oss-120b';
    }
    if (groq['gpt-oss-20b'].chars < groq['gpt-oss-20b'].limit) {
        return 'openai/gpt-oss-20b';
    }
    if (groq['kimi-k2-instruct'].chars < groq['kimi-k2-instruct'].limit) {
        return 'moonshotai/kimi-k2-instruct';
    }

    // All limits exhausted
    return null;
}

// ============ HISTORY ============

function getSessionPath(sessionId) {
    return path.join(getHistoryDir(), `${sessionId}.json`);
}

function saveSession(sessionId, data) {
    const sessionPath = getSessionPath(sessionId);

    // Load existing session to preserve metadata
    const existingSession = readJsonFile(sessionPath, null);

    const sessionData = {
        sessionId,
        createdAt: existingSession?.createdAt || parseInt(sessionId),
        lastUpdated: Date.now(),
        // Profile context - set once when session starts
        profile: data.profile || existingSession?.profile || null,
        customPrompt: data.customPrompt || existingSession?.customPrompt || null,
        // Conversation data
        conversationHistory: data.conversationHistory || existingSession?.conversationHistory || [],
        screenAnalysisHistory: data.screenAnalysisHistory || existingSession?.screenAnalysisHistory || [],
    };
    return writeJsonFile(sessionPath, sessionData);
}

function getSession(sessionId) {
    return readJsonFile(getSessionPath(sessionId), null);
}

function getAllSessions() {
    const historyDir = getHistoryDir();

    try {
        if (!fs.existsSync(historyDir)) {
            return [];
        }

        const files = fs
            .readdirSync(historyDir)
            .filter(f => f.endsWith('.json'))
            .sort((a, b) => {
                // Sort by timestamp descending (newest first)
                const tsA = parseInt(a.replace('.json', ''));
                const tsB = parseInt(b.replace('.json', ''));
                return tsB - tsA;
            });

        return files
            .map(file => {
                const sessionId = file.replace('.json', '');
                const data = readJsonFile(path.join(historyDir, file), null);
                if (data) {
                    return {
                        sessionId,
                        createdAt: data.createdAt,
                        lastUpdated: data.lastUpdated,
                        messageCount: data.conversationHistory?.length || 0,
                        screenAnalysisCount: data.screenAnalysisHistory?.length || 0,
                        profile: data.profile || null,
                        customPrompt: data.customPrompt || null,
                    };
                }
                return null;
            })
            .filter(Boolean);
    } catch (error) {
        console.error('Error reading sessions:', error.message);
        return [];
    }
}

function deleteSession(sessionId) {
    const sessionPath = getSessionPath(sessionId);
    try {
        if (fs.existsSync(sessionPath)) {
            fs.unlinkSync(sessionPath);
            return true;
        }
    } catch (error) {
        console.error('Error deleting session:', error.message);
    }
    return false;
}

function deleteAllSessions() {
    const historyDir = getHistoryDir();
    try {
        if (fs.existsSync(historyDir)) {
            const files = fs.readdirSync(historyDir).filter(f => f.endsWith('.json'));
            files.forEach(file => {
                fs.unlinkSync(path.join(historyDir, file));
            });
        }
        return true;
    } catch (error) {
        console.error('Error deleting all sessions:', error.message);
        return false;
    }
}

